#!/usr/bin/env node
// Builds the hand-off graph from each agent's "## Hand-offs" section (the single source of truth).
// Writes tools/handoffs.json, HANDOFFS.md, and web/app/handoffs.json (imported by the site).
// Usage: node tools/build-handoffs.mjs [--check]   (--check fails if outputs are stale or an agent is an orphan)
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "agents");
const kitOf = (fm) => fm;
const graph = {}, meta = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
  const name = f.replace(/\.md$/, "");
  const text = readFileSync(join(dir, f), "utf8");
  meta[name] = { model: (text.match(/^model:\s*(\S+)/m) || [])[1] };
  const sec = text.split(/^## Hand-offs\s*$/m)[1]?.split(/^## /m)[0] ?? "";
  graph[name] = [...sec.matchAll(/^- `([a-z0-9-]+)` — (.+)$/gm)].map((m) => ({ to: m[1], why: m[2].trim() }));
}
const names = Object.keys(graph);
const problems = [];
for (const [a, edges] of Object.entries(graph))
  for (const e of edges) if (!graph[e.to]) problems.push(`${a} hands off to unknown agent ${e.to}`);
const incoming = Object.fromEntries(names.map((n) => [n, 0]));
for (const [a, edges] of Object.entries(graph)) for (const e of edges) if (a !== "tech-lead") incoming[e.to]++;
const orphans = names.filter((n) => n !== "tech-lead" && incoming[n] === 0);
const noOutgoing = names.filter((n) => n !== "tech-lead" && graph[n].length === 0);

const id = (n) => n.replace(/-/g, "_");
const mermaid = ["flowchart LR", "  tech_lead[tech-lead<br/>orchestrator]"];
for (const [a, edges] of Object.entries(graph)) for (const e of edges) mermaid.push(`  ${id(a)}[${a}] --> ${id(e.to)}[${e.to}]`);
const rows = Object.entries(graph).filter(([, e]) => e.length).map(([a, e]) => `| \`${a}\` | ${e.map((x) => `\`${x.to}\` (${x.why})`).join("; ")} |`);
const md = `# Hand-off graph

Who hands off to whom. Generated by \`node tools/build-handoffs.mjs\` from each agent's \`## Hand-offs\` section — edit the agent file, not this one. \`tech-lead\` can delegate to every agent (see its delegation map).

\`\`\`mermaid
${mermaid.join("\n")}
\`\`\`

| Agent | Hands off to |
|---|---|
${rows.join("\n")}
`;
const json = JSON.stringify(graph, null, 1) + "\n";
const outs = [[join(root, "HANDOFFS.md"), md], [join(root, "tools/handoffs.json"), json], [join(root, "web/app/handoffs.json"), json]];

if (process.argv.includes("--check")) {
  const stale = outs.filter(([p, c]) => !existsSync(p) || readFileSync(p, "utf8") !== c).map(([p]) => p);
  if (stale.length) problems.push(`stale generated files (run node tools/build-handoffs.mjs): ${stale.join(", ")}`);
  if (orphans.length) problems.push(`no agent hands off to: ${orphans.join(", ")}`);
  if (noOutgoing.length) problems.push(`no Hand-offs section: ${noOutgoing.join(", ")}`);
  if (problems.length) { console.error(problems.map((p) => "✗ " + p).join("\n")); process.exit(1); }
  console.log(`✓ hand-off graph: ${names.length} agents, ${Object.values(graph).reduce((n, e) => n + e.length, 0)} edges, no orphans`);
} else {
  for (const [p, c] of outs) writeFileSync(p, c);
  console.log(`wrote graph: ${names.length} agents, ${Object.values(graph).reduce((n, e) => n + e.length, 0)} edges`);
  if (orphans.length) console.log("orphans (nobody hands off to them):", orphans.join(", "));
  if (noOutgoing.length) console.log("no outgoing:", noOutgoing.join(", "));
  if (problems.length) console.log(problems.join("\n"));
}
